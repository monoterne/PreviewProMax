import { mkdir, readdir, readFile, writeFile, copyFile } from "node:fs/promises";
import { resolve } from "node:path";

if (process.platform !== "darwin") process.exit(0);
const root = resolve(import.meta.dirname, "..");
const icons = resolve(root, "src-tauri/icons");
const source = resolve(icons, "PreviewProMax.icon");
const catalog = resolve(icons, "Assets.car");
const record = resolve(icons, "catalog.json");
const hash = new Bun.CryptoHasher("sha256");
for (const name of ["icon.json", ...(await readdir(resolve(source, "Assets"))).sort().map(name => `Assets/${name}`)]) {
  hash.update(name);
  hash.update(await readFile(resolve(source, name)));
}
const sourceHash = hash.digest("hex");
const compiler = Bun.spawnSync(["xcrun", "--find", "actool"], { stdout: "pipe", stderr: "pipe" });
if (compiler.exitCode !== 0) {
  try {
    const cached = JSON.parse(await readFile(record, "utf8"));
    const catalogHash = new Bun.CryptoHasher("sha256").update(await readFile(catalog)).digest("hex");
    if (cached.source === sourceHash && cached.catalog === catalogHash) {
      console.log("Using the verified icon catalog; full Xcode is not installed.");
      process.exit(0);
    }
  } catch { /* No usable cached catalog. */ }
  throw new Error("The icon catalog needs regeneration. Run bun run icons:mac with full Xcode 26+ installed, or use the catalog generated by macOS CI.");
}
const output = resolve(root, ".tmp/icon-catalog");
await mkdir(output, { recursive: true });
const compile = Bun.spawn([
  "xcrun", "actool", source, "--compile", output,
  "--output-format", "human-readable-text", "--notices", "--warnings",
  "--output-partial-info-plist", resolve(output, "Info.plist"),
  "--app-icon", "PreviewProMax", "--include-all-app-icons",
  "--target-device", "mac", "--minimum-deployment-target", "26.0", "--platform", "macosx",
], {
  // actool requires an open stdin. Tauri's closed stdin can crash ibtoold:
  // https://github.com/tauri-apps/tauri/issues/15315
  stdin: Bun.file("/dev/null"), stdout: "inherit", stderr: "inherit",
});
if (await compile.exited !== 0) throw new Error("Apple icon catalog compilation failed");
await copyFile(resolve(output, "Assets.car"), catalog);
const catalogHash = new Bun.CryptoHasher("sha256").update(await readFile(catalog)).digest("hex");
await writeFile(record, JSON.stringify({ source: sourceHash, catalog: catalogHash }, null, 2) + "\n");
console.log("Compiled the adaptive macOS icon catalog.");
